def cpt_anomaly(pipe: str, rel: str, flow: str) -> list[float]:
    """anomaly | pipe_cond, reliability, flow -- правило, а не таблица.

    Основной драйвер -- pipe_cond (скрытое гидравлическое состояние), а
    НЕ сырое пороговое значение расхода: диплом явно критикует одиночные
    пороговые правила (§3.1), поэтому в код заложен тот же принцип.
    reliability реализует эффект "объяснения прочь" (сценарий 3, §3.3):
    недостоверные показания оттягивают массу вероятности обратно к
    "норма", даже если расход выглядит аномальным.
    """
    base = {
        "норма":                  np.array([0.90, 0.07, 0.03]),
        "нарушена_герметичность": np.array([0.10, 0.85, 0.05]),
        "засор":                  np.array([0.75, 0.05, 0.20]),
    }[pipe].copy()

    if flow == "anomal_high":
        base += np.array([-0.10, 0.15, -0.05])
    elif flow == "anomal_low":
        base += np.array([-0.05, -0.05, 0.10])

    if rel == "недостоверная":
        base += np.array([0.35, -0.25, -0.10])
    elif rel == "сомнительная":
        base += np.array([0.12, -0.08, -0.04])

    base = np.clip(base, 0.01, None)
    return (base / base.sum()).tolist()


