# Температура вне графика -- слабый эффект и смещённый в сторону деградации:
# отклонение на пару градусов чаще означает ошибку теплоснабжающей
# организации или начинающуюся деградацию, чем отказ прибора.
# Норма температуры определяется температурным графиком по усреднённой
# уличной температуре, допуск ±3% (ПТЭ тепловых энергоустановок,
# Приказ Минэнерго России от 24.03.2003 № 115) -- см. README.
MULT_TEMP_DEVICE = (1.0, 1.50, 1.15)

# Давление -- один из главных параметров, эффект сильный и смещённый
# в сторону неисправности.
MULT_PRESSURE_DEVICE = (1.0, 3.00, 4.00)


def cpt_device(pressure: str, temperature: str, calibration: str, age: str) -> list[float]:
    v = np.asarray(CPT_DEVICE_BASE[(age, calibration)], dtype=float)
    if temperature == "otklonenie":
        v = _odds(v, MULT_TEMP_DEVICE)
    if pressure == "otklonenie":
        v = _odds(v, MULT_PRESSURE_DEVICE)
    return (v / v.sum()).tolist()


