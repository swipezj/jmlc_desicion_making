# ===========================================================================
# reliability | flow, calibration, age
# ===========================================================================
# 27 строк -- задаётся правилом, а не таблицей.
#
# Модель комбинирования: "худший фактор задаёт уровень" (noisy-max), а не
# аддитивная и не noisy-OR. Обоснование эксперта: когда плохих факторов
# несколько, это почти всегда ОДНА первопричина, постепенно нарушавшая
# работу системы, а не несколько независимых поломок. Аддитивная модель
# считала бы один и тот же сигнал несколько раз и выдавала бы
# P(недостоверная) ~0.95 там, где такой уверенности нет.
#
# ДУГА pipe_cond -> reliability УБРАНА (была добавлена при первом
# пересмотре и снята по итогам повторного опроса). Причина -- не
# статистическая, а смысловая: `reliability` означает "прибор исправно
# измеряет", а не "показания отражают реальное потребление". При утечке
# прибор меряет верно, просто мерить ему нечего -- это и есть узел
# `anomaly`, то есть ПОТОМОК гидравлики, а не соучастник.
#
# Побочный эффект был вреден: reliability -- потомок pipe_cond и родитель
# anomaly, поэтому чем сильнее свидетельство за разгерметизацию, тем выше
# была P(недостоверная), а та через "объяснение прочь" гасила вывод об
# утечке. Сеть тем меньше верила в утечку, чем больше было улик за утечку.
SEVERITY_RELIABILITY: dict[str, dict[str, float]] = {
    "flow":        {"norma": 0.0, "anomal_high": 0.55, "anomal_low": 0.55},
    "calibration": {"v_norme": 0.0, "priblizhaetsya": 0.15, "istek": 0.35},
    "age":         {"lt_3": 0.0, "3_7": 0.25, "gt_7": 0.60},
}
# вклад НЕхудших факторов сверх максимума
RELIABILITY_ALPHA = 0.20
RELIABILITY_GOOD = np.array([0.95, 0.04, 0.01])   # тяжесть 0
RELIABILITY_BAD = np.array([0.05, 0.25, 0.70])    # тяжесть 1


def cpt_reliability(flow: str, calibration: str, age: str) -> list[float]:
    s = [SEVERITY_RELIABILITY["flow"][flow],
         SEVERITY_RELIABILITY["calibration"][calibration],
         SEVERITY_RELIABILITY["age"][age]]
    severity = min(1.0, max(s) + RELIABILITY_ALPHA * (sum(s) - max(s)))
    v = RELIABILITY_GOOD + (RELIABILITY_BAD - RELIABILITY_GOOD) * severity
    return (v / v.sum()).tolist()


