def _odds(base, mult) -> np.ndarray:
    """Домножить шансы состояний на mult и нормировать.

    Ключевое свойство: mult = (1, 1, 1) возвращает base без изменений.
    Именно поэтому таблицы из диплома сохраняются точно на срезе
    «новый родитель в норме».
    """
    v = np.asarray(base, dtype=float) * np.asarray(mult, dtype=float)
    return v / v.sum()


